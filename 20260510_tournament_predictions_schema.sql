begin;

create table if not exists public.football_tournament_prediction_rules (
    id bigint generated by default as identity primary key,
    competition_season_id bigint not null references public.competition_seasons(id) on delete cascade,
    rules jsonb not null default '{
        "groupPosition": 1,
        "groupPerfectBonus": 3,
        "qualifiedThird": 2,
        "knockoutByRound": {
            "round_of_32": 5,
            "round_of_16": 10,
            "quarterfinals": 12,
            "semifinals": 15,
            "third_place": 20,
            "final": 25
        },
        "champion": 0,
        "awards": {
            "mvp": 0,
            "bestGoalkeeper": 0,
            "topScorer": 0
        }
    }'::jsonb,
    created_at timestamptz not null default timezone('utc', now()),
    updated_at timestamptz not null default timezone('utc', now()),
    unique (competition_season_id)
);

create table if not exists public.football_tournament_predictions (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references auth.users(id) on delete cascade,
    sport_id bigint not null references public.sports(id) on delete cascade,
    competition_id bigint not null references public.competitions(id) on delete cascade,
    competition_season_id bigint not null references public.competition_seasons(id) on delete cascade,
    status text not null check (status in ('open', 'locked', 'scored', 'cancelled')),
    payload jsonb not null default '{}'::jsonb,
    points integer,
    points_breakdown jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default timezone('utc', now()),
    updated_at timestamptz not null default timezone('utc', now()),
    scored_at timestamptz,
    unique (user_id, competition_season_id)
);

create table if not exists public.football_tournament_results (
    competition_season_id bigint primary key references public.competition_seasons(id) on delete cascade,
    champion_participant_id bigint references public.participants(id) on delete set null,
    mvp_participant_id bigint references public.participants(id) on delete set null,
    best_goalkeeper_participant_id bigint references public.participants(id) on delete set null,
    top_scorer_participant_id bigint references public.participants(id) on delete set null,
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default timezone('utc', now()),
    updated_at timestamptz not null default timezone('utc', now())
);

alter table public.football_tournament_prediction_rules enable row level security;
alter table public.football_tournament_predictions enable row level security;
alter table public.football_tournament_results enable row level security;

commit;
